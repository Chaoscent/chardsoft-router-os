def get_wifi_status():

    installed = has_hostapd()

    running = {
        name: installed and is_hostapd_running(name)
        for name in get_networks()
    }

    return {
        "installed": installed,
        "running": running,
        "config_dir": HOSTAPD_DIR
    }


