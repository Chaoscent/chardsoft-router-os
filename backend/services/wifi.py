def config_path(interface):

    return os.path.join(HOSTAPD_DIR, f"chaos-{interface}.conf")


def unit_name(interface):

    return HOSTAPD_UNIT.format(interface)


def config_files():
    """
    Every hostapd config Chardsoft Router OS wrote (for factory reset and
    uninstall).
    """

    try:
        names = os.listdir(HOSTAPD_DIR)
    except OSError:
        names = []

    files = [
        os.path.join(HOSTAPD_DIR, n) for n in sorted(names)
        if n.startswith("chaos-") and n.endswith(".conf")
    ]

    if is_legacy_config():
        files.append(LEGACY_CONF_FILE)

    return files


def wide_channel(band, channel, width):
    """
    How a channel spans a width: {"ht40": "+"/"-", "center": n} (center
    channel index for VHT/HE), {} for 20 MHz, or None when the channel
    can't (the wider block would leave the band).
    """

    if width == 20:
        return {}

    if band == "2.4":
        # HT40+ needs channel + 4, HT40- channel - 4 (1..13).
        return {"ht40": "+" if channel <= 7 else "-"}

    if band == "5":
        # Blocks 36-48 and 149-161: pairs (36,40), (44,48), ...
        first = 36 if channel <= 48 else 149
        pair_low = (channel - first) % 8 == 0
        info = {"ht40": "+" if pair_low else "-"}
        if width == 80:
            info["center"] = first + 6
        else:
            info["center"] = channel + 2 if pair_low else channel - 2
        return info

    # 6 GHz: 20 MHz channels 1, 5, 9, ...; a width covers width/20 of them.
    span = width // 20
    block = (channel - 1) // (4 * span)
    first = block * 4 * span + 1
    last = first + 4 * (span - 1)

    if last > 233:
        return None

    return {"center": (first + last) // 2}


def render_hostapd_config(settings):

    band = BANDS[settings["band"]]

    lines = [
        "# Generated by Chardsoft Router OS. Do not edit by hand.",
        "# Changes are overwritten from the WiFi page.",
        f"# Access point on {settings['interface']} (chaos-hostapd@{settings['interface']}).",
        "",
        f"interface={settings['interface']}",
        # One LAN: the access point joins the LAN bridge.
        *([f"bridge={BRIDGE}"] if bridges_interface(settings["interface"]) else []),
        "driver=nl80211",
        "ctrl_interface=/var/run/hostapd",
        "ctrl_interface_group=0",
        "",
        # Hex form needs no escaping for any SSID characters.
        f"ssid2={settings['ssid'].encode('utf-8').hex()}",
        "utf8_ssid=1",
        f"ignore_broadcast_ssid={1 if settings['hidden'] else 0}",
        "",
        f"country_code={settings['country']}",
        "ieee80211d=1",
        f"hw_mode={band['hw_mode']}",
        f"channel={settings['channel']}",
        "wmm_enabled=1"
    ]

    width = settings.get("width") or 20
    wide = wide_channel(settings["band"], settings["channel"], width) or {}

    if settings["band"] == "6":

        # 6 GHz is HE (802.11ax) only; HT/VHT are not used there. The
        # operating class sets the width, the center channel its place.
        lines += [
            f"op_class={OP_CLASS_6GHZ[width]}",
            "ieee80211ax=1"
        ]

        if width > 20:
            lines += [
                f"he_oper_chwidth={ {40: 0, 80: 1, 160: 2}[width] }",
                f"he_oper_centr_freq_seg0_idx={wide['center']}"
            ]

    else:

        lines.append("ieee80211n=1")

        if width >= 40:
            lines.append(f"ht_capab=[HT40{wide['ht40']}]")

        if settings["band"] == "5":

            lines.append("ieee80211ac=1")

            if width >= 40:
                lines += [
                    # 0: 20/40 MHz, 1: 80 MHz.
                    f"vht_oper_chwidth={1 if width == 80 else 0}",
                    f"vht_oper_centr_freq_seg0_idx={wide['center']}"
                ]

    lines.append(f"ap_isolate={1 if settings['isolate_clients'] else 0}")

    security = settings["security"]

    if security != "open":

        key_mgmt = {
            "wpa2": "WPA-PSK",
            "wpa2-wpa3": "WPA-PSK SAE",
            "wpa3": "SAE"
        }[security]

        lines += [
            "",
            "auth_algs=1",
            "wpa=2",
            f"wpa_key_mgmt={key_mgmt}",
            "rsn_pairwise=CCMP",
            f"wpa_passphrase={settings['password']}"
        ]

        # WPA3 requires protected management frames.
        if security == "wpa3":
            lines.append("ieee80211w=2")
        elif security == "wpa2-wpa3":
            lines.append("ieee80211w=1")

        if security != "wpa2":
            lines.append(f"sae_password={settings['password']}")

        # 6 GHz only allows hash-to-element SAE.
        if settings["band"] == "6":
            lines.append("sae_pwe=1")

    if guest_enabled(settings):
        lines += render_guest_bss(settings)

    return "\n".join(lines) + "\n"


def security_lines(security, password, band):

    if security == "open":
        return []

    lines = [
        "auth_algs=1",
        "wpa=2",
        "wpa_key_mgmt=" + {"wpa2": "WPA-PSK", "wpa2-wpa3": "WPA-PSK SAE", "wpa3": "SAE"}[security],
        "rsn_pairwise=CCMP",
        f"wpa_passphrase={password}"
    ]

    if security == "wpa3":
        lines.append("ieee80211w=2")
    elif security == "wpa2-wpa3":
        lines.append("ieee80211w=1")

    if security != "wpa2":
        lines.append(f"sae_password={password}")

    if band == "6":
        lines.append("sae_pwe=1")

    return lines


def render_guest_bss(settings):
    """The guest network: a second BSS on the same radio and channel."""

    guest = settings["guest"]
    interface = guest_interface(settings["interface"])
    bssid = guest_bssid(settings["interface"])

    return [
        "",
        f"# Guest network ({interface}): internet only, guests cannot see each other.",
        f"bss={interface}",
        *([f"bssid={bssid}"] if bssid else []),
        "ctrl_interface=/var/run/hostapd",
        f"ssid2={guest['ssid'].encode('utf-8').hex()}",
        "utf8_ssid=1",
        "ignore_broadcast_ssid=0",
        "wmm_enabled=1",
        "ap_isolate=1",
        *security_lines(guest["security"], guest["password"], settings["band"])
    ]


def install_hostapd_config(content, path):

    fd, tmp = tempfile.mkstemp(
        prefix="chaos-hostapd-",
        suffix=".conf"
    )

    try:

        with os.fdopen(fd, "w") as f:
            f.write(content)

        ok, result = run_command(privileged([
            "mkdir",
            "-p",
            HOSTAPD_DIR
        ]))

        if not ok:
            return False, result

        # 600: the file contains the Wi-Fi password.
        return run_command(privileged([
            "install",
            "-m",
            "600",
            tmp,
            path
        ]))

    finally:

        os.unlink(tmp)


def set_networkmanager_managed(interface, managed):
    """
    NetworkManager must leave the interface alone while hostapd
    runs the access point.
    """

    if not which("nmcli"):
        return True, "OK"

    return run_command(privileged([
        "nmcli",
        "device",
        "set",
        interface,
        "managed",
        "yes" if managed else "no"
    ]))


def get_hostapd_error(interface):

    ok, output = run_command(privileged([
        "journalctl",
        "-u",
        unit_name(interface),
        "-n",
        "5",
        "--no-pager",
        "-o",
        "cat"
    ]))

    return output if ok and output else "hostapd failed to start."


